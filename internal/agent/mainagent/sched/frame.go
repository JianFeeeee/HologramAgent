package sched

// frame.go —— 调度器看到的**帧取面**（挂起/恢复 + 日志归因）。
//
// ## 为什么是接口而不是具体类型
//
// 调度器与帧只有两处接触：
//
//	Suspend(t, f)    把**整个现场**压进中断栈（只存不读）
//	SourceOf(t, f)   日志归因（只读"这条输入是谁送来的"）
//
// 它不读帧里的消息、工具、预算 —— 那些属于 agentloop。
// 所以本包只要两个最小取面，具体帧类型（`mainagent.TaskFrame`）由
// 本类型自己的 frame.go 定义。这不是"跨类型共享"：sched 是本类型内部
// 的一个包，它认识的东西仍然是本类型的东西。
